              f"Whether the joint disadvantage of race, gender, education, income and place is “more than the sum of its parts” is a recurring question in quantitative intersectionality research, and the answer depends on the scale of analysis. Using {n0(NA)} households from the 2023 Brazilian national household survey, we combine additive-scale interaction (RERI), multiplicative-scale interaction, the joint-disparity decomposition, cumulative-disadvantage gradients and intersectional multilevel analysis of individual heterogeneity and discriminatory accuracy (MAIHDA) across 160 strata.",
