def build_xlsx():
    import openpyxl
    from openpyxl.styles import Font, PatternFill, Alignment
    wb = openpyxl.Workbook(); ws = wb.active; ws.title = "README"
    lines = ["Supplementary data: the 160 intersectional strata (PNADC 2023, Q4).",
             "Strata are the cross-classification of race (2) x sex (2) x education (4) x income (5) x residence (2).",
             "Predicted probabilities come from logistic multilevel models (lme4): 'null' = Model A with empirical-Bayes shrinkage; 'additive' = Model B main effects only; 'full' = Model B main effects + stratum residual.",
             "u = Model B stratum residual (log-odds); se_u = conditional standard error; z = u/se_u. About 5% of strata are expected to exceed |z| = 1.96 by chance.",
             "obs_unweighted / obs_weighted = observed prevalence in the stratum (weighted uses the survey weight). MAIHDA models are unweighted.",
             "Labels: Race N = non-Black, B = Black; Education: 'no schooling/incomplete primary', 'complete primary/incomplete secondary', 'complete secondary', 'tertiary'; Income in minimum wages per capita."]
    for i, l in enumerate(lines, 1): ws.cell(i, 1, l)
    ws.column_dimensions["A"].width = 150
    lab = {"nao_negra": "Non-Black", "negra": "Black", "homem": "Man", "mulher": "Woman", "sem_fund": "No schooling/incomplete primary",
           "fund_med": "Complete primary/incomplete secondary", "medio_comp": "Complete secondary", "superior": "Tertiary", "q1": "<=1/4", "q2": ">1/4-1/2",
           "q3": ">1/2-1", "q4": ">1-2", "mais_2sm": ">2", "urbano": "Urban", "rural": "Rural"}
    for dd, nome in [("ia_total", "Any food insecurity"), ("ia_grave", "Severe food insecurity")]:
        w = wb.create_sheet(nome)
        hdr = ["Race", "Sex", "Education", "Income (MW)", "Residence", "n", "obs_unweighted", "obs_weighted", "pred_null_shrunk", "pred_additive", "pred_full", "u", "se_u", "z"]
        w.append(hdr)
        s = m3[m3.desfecho == dd].sort_values("p_completo", ascending=False)
        for r in s.itertuples():
            parts = r.estrato.split("__")
            w.append([lab.get(parts[0], parts[0]), lab.get(parts[1], parts[1]), lab.get(parts[2], parts[2]), lab.get(parts[3], parts[3]), lab.get(parts[4], parts[4]),
                      int(r.n), round(r.obs_naoponderada, 4), round(r.obs_ponderada, 4), round(r.p_nulo_shrunk, 4), round(r.p_aditivo, 4), round(r.p_completo, 4),
                      round(r.u, 4), round(r.se_u, 4), round(r.z, 2)])
        for c in w[1]: c.font = Font(bold=True); c.fill = PatternFill("solid", fgColor="E7E6E6"); c.alignment = Alignment(wrap_text=True)
        for col, wd in zip("ABCDEFGHIJKLMN", [11, 8, 36, 12, 10, 8, 14, 13, 16, 14, 11, 9, 9, 8]): w.column_dimensions[col].width = wd
        w.freeze_panes = "A2"
    wb.save(OUT / "Supplementary_data_strata.xlsx")


